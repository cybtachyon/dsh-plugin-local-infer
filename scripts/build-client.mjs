#!/usr/bin/env node
/**
 * build-client: produce the lazy-CJS browser artifact dsh/client.js.
 *
 * Two steps:
 *   1. esbuild bundles packages/client/src/index.ts to the CJS intermediate
 *      dsh/.build/client.cjs. react and @deepseek-ai/dsh-client-ui-primitives
 *      stay external: they resolve at runtime through the shell's frozen
 *      platform module table, so the bundle must emit exactly those two
 *      runtime requires.
 *   2. The intermediate is wrapped in the window.__ModuleLoader__.load
 *      contract and written to dsh/client.js. esbuild's CJS external shim
 *      resolves `require` dynamically, so inside the factory it picks up the
 *      injected platform-table require.
 *
 * Run after `tsc -b` (the root build script chains the two). The output is
 * deterministic: a second run writes a byte-identical dsh/client.js.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import esbuild from 'esbuild'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const entry = join(root, 'packages/client/src/index.ts')
const intermediate = join(root, 'dsh/.build/client.cjs')
const artifact = join(root, 'dsh/client.js')

// Classic JSX transform (jsxFactory / jsxFragment): the automatic runtime
// (react/jsx-runtime) is not in the shell's platform module table.
await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['react', '@deepseek-ai/dsh-client-ui-primitives'],
  outfile: intermediate,
  jsx: 'transform',
  jsxFactory: 'react.createElement',
  jsxFragment: 'react.Fragment',
})

const bundle = readFileSync(intermediate, 'utf8')
const output = `// generated by scripts/build-client.mjs. Do not edit.
window.__ModuleLoader__.load({ id: 'dsh-plugin-local-infer', factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${bundle}
    return module.exports;
} });
`
writeFileSync(artifact, output)
console.log(`wrote dsh/client.js (${output.length} bytes)`)
